/* ── run ──────────────────────────────────────────────────────────────── */
const { head, tail } = shell();
const stale = [];
let wrote = 0;
let same = 0;

const pages = [
  {
    file: 'services.html',
    url: `${SITE}/services`,
    title: 'Web Development & SEO Services in India | Rushan Haque',
    description:
      'Website design, e-commerce, web applications, SEO and GEO — every service in one place, built from scratch by one person in Moradabad, India.',
    main: servicesHub(),
  },
  {
    file: 'areas-served.html',
    url: `${SITE}/areas-served`,
    title: 'Areas Served Across Uttar Pradesh | Rushan Haque',
    description:
      'Website design and development across Moradabad, Rampur, Sambhal, Amroha, Bijnor, Meerut, Bareilly, Aligarh, Lucknow, Kanpur and Delhi NCR — and remote worldwide.',
    main: areasHub(),
  },
  ...SERVICES.map((s) => ({
    file: `${s.slug}.html`,
    url: `${SITE}/${s.slug}`,
    title: s.title,
    description: s.description,
    main: servicePage(s),
  })),
  ...LOCATIONS.map((l) => ({
    file: `${l.slug}.html`,
    url: `${SITE}/${l.slug}`,
    title: l.title,
    description: l.description,
    main: locationPage(l),
  })),
];

for (const p of pages) {
  const html =
    buildHead(head, p) +
    '<!-- Page Content Start -->\n' +
    '    <main id="mxd-page-content" class="mxd-page-content inner-page-content rh-local">\n\n' +
    p.main +
    '\n    </main>\n    ' +
    tail;

  const path = join(ROOT, p.file);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;

  /* The committed file also carries the JSON-LD that scripts/seo-schema.mjs
     injects afterwards, which this script deliberately leaves empty. Compare
     with that block collapsed on both sides, or every page would look stale
     the moment the schema step ran and --check could never pass. */
  const withoutSchema = (s) =>
    s == null ? null : s.replace(/<!-- rh:schema[\s\S]*?<!-- \/rh:schema -->/, '<!--schema-->');

  if (withoutSchema(current) === withoutSchema(html)) { same++; continue; }
  if (CHECK) { stale.push(p.file); continue; }
  writeFileSync(path, html);
  wrote++;
}

if (CHECK && stale.length) {
  console.error(
    `\nGenerated pages are out of date (${stale.length}): ${stale.slice(0, 6).join(', ')}` +
    `${stale.length > 6 ? ', …' : ''}\nRun "npm run pages" and commit the result.`
  );
  process.exit(1);
}

console.log(
  CHECK
    ? `Generated pages are current (${pages.length}).`
    : `Pages OK — ${wrote} written, ${same} already current (${pages.length} total).`
);
