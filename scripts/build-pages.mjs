/* scripts/build-pages.mjs — generate the service and location pages.
 *
 * Every generated page is assembled from contact.html's own shell, so the
 * navigation, footer, stylesheets and scripts are byte-identical to the rest
 * of the site and can never drift out of sync with it. Only the <head> meta
 * and the <main> content are generated.
 *
 * The FAQ blocks are rendered here AND read by scripts/seo-schema.mjs from the
 * same data files, so the visible answers and the FAQPage markup are guaranteed
 * to match — Google only honours FAQ markup whose answers are on the page.
 *
 *   node scripts/build-pages.mjs           # write
 *   node scripts/build-pages.mjs --check   # verify committed pages are current
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { SERVICES } from '../data/seo-services.mjs';
import { LOCATIONS, locationFAQ } from '../data/seo-locations.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const SITE = 'https://www.rushanhaque.in';

/* ── html helpers ─────────────────────────────────────────────────────── */
const esc = (s) =>
  String(s == null ? '' : s)
    .replace(/&(?!(?:amp|lt|gt|quot|#39|mdash|ndash|nbsp|hellip);)/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');

/* Content strings are authored with entities already in them (&amp;, &mdash;),
   so they pass through as written; only interpolated values get escaped. */
const raw = (s) => String(s == null ? '' : s);

/* ── shell ────────────────────────────────────────────────────────────── */
function shell() {
  const src = readFileSync(join(ROOT, 'contact.html'), 'utf8');
  const START = '<!-- Page Content Start -->';
  const END = '<!-- Page Content End -->';
  const i = src.indexOf(START);
  const j = src.indexOf(END);
  if (i < 0 || j < 0) throw new Error('build-pages: page content markers missing in contact.html');
  return { head: src.slice(0, i), tail: src.slice(j) };
}

function buildHead(head, { url, title, description }) {
  let h = head;
  const rep = (find, replace, label) => {
    if (!h.includes(find)) throw new Error(`build-pages: head anchor missing (${label})`);
    h = h.split(find).join(replace);
  };

  rep('<title>Hire a Web Developer in Moradabad | Rushan Haque</title>',
      `<title>${raw(title)}</title>`, 'title');
  rep('content="Start a website project with Rushan Haque — web developer and designer in Moradabad, India. Custom websites, ecommerce and web apps. Get a quote today."',
      `content="${raw(description)}"`, 'description');
  rep(`<link rel="canonical" href="${SITE}/contact">`,
      `<link rel="canonical" href="${url}">`, 'canonical');
  rep(`<meta property="og:url" content="${SITE}/contact">`,
      `<meta property="og:url" content="${url}">`, 'og:url');
  rep('content="Hire a Web Developer in Moradabad — Rushan Haque">',
      `content="${raw(title).replace(/ \| Rushan Haque$/, ' — Rushan Haque')}">`, 'og/tw title');
  rep('content="Start a website project — custom websites, ecommerce and web apps, built in Moradabad.">',
      `content="${raw(description)}">`, 'og/tw desc');

  /* schema is regenerated by scripts/seo-schema.mjs — leave only the markers */
  h = h.replace(
    /[ \t]*<!-- rh:schema[\s\S]*?<!-- \/rh:schema -->/,
    '    <!-- rh:schema — generated by scripts/seo-schema.mjs, do not edit by hand -->\n    <!-- /rh:schema -->'
  );
  return h;
}

