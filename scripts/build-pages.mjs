/* ── assemble a service page ──────────────────────────────────────────── */
function servicePage(svc) {
  const byslug = Object.fromEntries(SERVICES.map((s) => [s.slug, s]));
  let n = 0;
  const no = () => String(++n).padStart(2, '0');

  let main = headline({
    eyebrow: svc.eyebrow,
    mark: 'S',
    h1: svc.h1,
    answer: svc.answer,
    facts: svc.facts,
  });

  for (const sec of svc.sections) {
    main += sectionOpen(no(), sec.h2.split(' ').slice(0, 2).join(' '), sec.h2, sec.lede || '');
    if (sec.prose) main += proseBlock(sec.prose);
    if (sec.items) main += bentoBlock(sec.items);
    main += sectionClose;
  }

  main += faqSection(no(), svc.faq);

  const rel = (svc.related || [])
    .filter((s) => byslug[s])
    .map((s) => [`/${s}`, byslug[s].h1, byslug[s].nav]);
  main += relatedSection(no(), rel);

  main += ctaSection('Send the brief &mdash; or the half-formed version of it &mdash; and you will get a quote with a timeline attached.');

  return main;
}

/* ── assemble a location page ─────────────────────────────────────────── */
function locationPage(loc) {
  let n = 0;
  const no = () => String(++n).padStart(2, '0');

  let main = headline({
    eyebrow: loc.city,
    mark: loc.city.slice(0, 1).toUpperCase(),
    h1: `Website designer in ${loc.city}`,
    answer: loc.answer,
    facts: [
      ['Based in', 'Moradabad, Uttar Pradesh'],
      ['Serving', `${loc.city}, ${loc.region}`],
      ['Distance', loc.distance.replace(/^about /, '')],
    ],
  });

  main += sectionOpen(no(), 'Local context', loc.industry.h2, loc.industry.lede);
  main += proseBlock(loc.industry.prose);
  main += sectionClose;

  /* City-specific, not the same six cards on every page.
     An identical services grid on ten city pages made each page roughly half
     the same document as every other one — which is the shape Google's spam
     policy calls a doorway network. These three items are written for this
     city's trade, and the shared service list below is a compact set of links
     instead of ten repetitions of the same six paragraphs. */
  /* "a Aligarh website" reads as a typo to exactly the reader you are trying
     to convince. Article choice follows the sound, not the spelling. */
  const article = /^[aeiou]/i.test(loc.city) ? 'an' : 'a';

  main += sectionOpen(no(), 'The brief',
    `What ${article} ${loc.city} website has to do`,
    `The general answer is the same everywhere. The specific one is not &mdash; and in ${loc.city} it usually comes down to these.`);
  main += bentoBlock(loc.needs);
  main += sectionClose;

  main += sectionOpen(no(), 'Services', 'Everything on offer',
    'Each of these is a service in its own right. Follow any one for what it involves.');
  main += `          <div class="mxd-block">
            <div class="container-fluid p-0">
              <div class="row g-0">
                <div class="col-12 mxd-grid-item">
                  <ul class="rh-local__areas rh-local__services">
${SERVICES.map((s) => `                    <li class="a-reveal"><a class="a-meta" href="/${s.slug}">${raw(s.nav)}</a></li>`).join('\n')}
                  </ul>
                </div>
              </div>
            </div>
          </div>
`;
  main += sectionClose;

  main += faqSection(no(), locationFAQ(loc));

  /* Cross-link to the four cities adjacent to this one in the list, wrapping
     at the ends. Taking a fixed slice instead would point every page at the
     same three cities, leaving the rest with a single inbound link from the
     hub — which is close enough to orphaned that Google treats them as low
     value. A rotating window gives every city roughly equal inbound links. */
  const i = LOCATIONS.findIndex((l) => l.slug === loc.slug);
  const neighbours = [1, 2, 3, 4]
    .map((k) => LOCATIONS[(i + k) % LOCATIONS.length])
    .filter((l) => l.slug !== loc.slug);

  const rel = [
    ['/website-designer-in-moradabad', 'Website designer in Moradabad', 'Base'],
    ...neighbours.map((l) => [`/${l.slug}`, `Website designer in ${l.city}`, l.region]),
    ['/areas-served', 'Every area served', 'All cities'],
  ];
  main += relatedSection(no(), rel);

  main += ctaSection(`Tell me what the site has to do for your ${loc.city} business, and you will get a quote with a timeline attached.`);

  return main;
}

